  function localizeCiv(name) {
    if (!name) return name;
    // Normalize to canonical English title-case for lookup.
    const canonical = String(name).trim().replace(/\b\w/g, c => c.toUpperCase());
    const dict = CIVS[currentLang];
    return (dict && dict[canonical]) || canonical;
  }

  const STORAGE_KEY = 'displayLang';

  function detectSystemLang() {
    const nav = (navigator.language || navigator.userLanguage || 'en').toLowerCase();
    if (nav.startsWith('pt')) return 'pt-BR';
    if (nav.startsWith('zh')) return 'zh';
    const short = nav.slice(0, 2);
    if (STRINGS[short]) return short;
    return 'en';
  }

  function getStoredLang() {
    try { return localStorage.getItem(STORAGE_KEY) || 'auto'; }
    catch { return 'auto'; }
  }

  function resolveLang() {
    const stored = getStoredLang();
    if (stored === 'auto' || !stored) return detectSystemLang();
    return STRINGS[stored] ? stored : 'en';
  }

  let currentLang = resolveLang();

  function t(key, vars) {
    const dict = STRINGS[currentLang] || STRINGS.en;
    let s = dict[key] ?? STRINGS.en[key] ?? key;
    if (vars) {
      for (const k of Object.keys(vars)) {
        s = s.replaceAll('{' + k + '}', String(vars[k]));
      }
    }
    return s;
  }

  function setLang(code) {
    try { localStorage.setItem(STORAGE_KEY, code || 'auto'); } catch {}
    currentLang = resolveLang();
  }

  window.i18n = { LANGS, t, setLang, getLang: () => currentLang, getStored: getStoredLang, localizeCiv };
  window.t = t;
  window.localizeCiv = localizeCiv;
